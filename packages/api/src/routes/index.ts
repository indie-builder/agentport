import type { FastifyInstance } from 'fastify';
import { registerAgentRoutes } from '../features/agents/routes.js';
import { registerAuditRoutes } from '../features/audit/routes.js';
import { registerAuth } from '../features/auth/routes.js';
import { registerChatRoutes } from '../features/chat/routes.js';
import { registerEvalRoutes } from '../features/eval/routes.js';
import { registerExportRoutes } from '../features/export/routes.js';
import { registerImportRoutes } from '../features/import/routes.js';
import { registerKnowledgeContentRoutes } from '../features/knowledge/content-routes.js';
import { registerFaqRoutes } from '../features/knowledge/faq-routes.js';
import { registerKnowledgeImageRoutes } from '../features/knowledge/image-routes.js';
import { registerKnowledgePackageRoutes } from '../features/knowledge/package-routes.js';
import { registerRetrievalEvaluationRoutes } from '../features/knowledge/retrieval-evaluation.js';
import { registerKnowledgeRoutes } from '../features/knowledge/routes.js';
import { registerSourceRoutes } from '../features/knowledge/source-routes.js';
import { registerWikiRoutes } from '../features/knowledge/wiki-routes.js';
import { registerMarketRoutes } from '../features/market/routes.js';
import { registerMemoryChangeRoutes } from '../features/memory/changes.js';
import { registerPersonalMemoryRoutes } from '../features/memory/routes.js';
import { registerMemoryReviewRoutes } from '../features/memory-reviews/routes.js';
import { registerOpsRoutes } from '../features/ops/routes.js';
import { registerOutputShareRoutes } from '../features/output-shares/routes.js';
import { registerOverviewRoutes } from '../features/overview/routes.js';
import { registerPluginRoutes } from '../features/plugins/routes.js';
import { registerRunRoutes } from '../features/runs/routes.js';
import { registerRuntimeEnvironmentRoutes } from '../features/runtime-environments/routes.js';
import { createInvoker } from '../features/servers/agent-invoker.js';
import { registerAgentToolsEndpoint } from '../features/servers/agent-tools-endpoint.js';
import { registerMcpEndpoint } from '../features/servers/mcp-endpoint.js';
import { registerServerRoutes } from '../features/servers/routes.js';
import { registerSkillRoutes } from '../features/skills/routes.js';
import { registerErrorHandler } from '../plugins/errors.js';
import { registerHealthRoutes } from './health.js';

export async function registerRoutes(app: FastifyInstance) {
  registerErrorHandler(app);
  await registerAuth(app);
  await registerHealthRoutes(app);
  await registerServerRoutes(app);
  await registerMcpEndpoint(app);
  registerAgentToolsEndpoint(app, createInvoker(app));
  await registerAgentRoutes(app);
  await registerRuntimeEnvironmentRoutes(app);
  await registerSkillRoutes(app);
  registerMarketRoutes(app);
  registerExportRoutes(app);
  registerImportRoutes(app);
  registerKnowledgePackageRoutes(app);
  registerKnowledgeRoutes(app);
  registerKnowledgeContentRoutes(app);
  registerKnowledgeImageRoutes(app);
  registerSourceRoutes(app);
  registerWikiRoutes(app);
  registerFaqRoutes(app);
  registerRetrievalEvaluationRoutes(app);
  // 插件 ZIP 复用 import 路由注册的 application/zip 解析器，必须在其后注册。
  await registerPluginRoutes(app);
  await registerAuditRoutes(app);
  await registerChatRoutes(app);
  registerOutputShareRoutes(app);
  registerPersonalMemoryRoutes(app);
  registerMemoryReviewRoutes(app);
  registerMemoryChangeRoutes(app);
  registerEvalRoutes(app);
  registerOverviewRoutes(app);
  registerOpsRoutes(app);
  registerRunRoutes(app);
}
